<h2>Why Albania, Why Now</h2>
<p class="subtitle">The government is building the infrastructure for us.</p>
<div class="two-col">
  <div>
    <div class="success-box">
      <h3>Government Push for Cashless</h3>
      <ul>
        <li>PM Rama: cashless Albania by 2030</li>
        <li>Cash limits lowered: 100K ALL (B2B), 500K ALL (individuals)</li>
        <li>All businesses must accept cards by end of 2026</li>
        <li>SEPA integration: operational October 2025</li>
        <li>Instant payments infrastructure being built</li>
      </ul>
    </div>
    <div class="success-box" style="margin-top: 16px;">
      <h3>Fiskalizimi = Our Secret Weapon</h3>
      <ul>
        <li>Every receipt has a QR code since 2021</li>
        <li>Verified by the state in real-time (NIVF)</li>
        <li>Contains: merchant ID, items, amounts, VAT, date</li>
        <li>Third-party APIs exist (fature.al)</li>
        <li>Better infrastructure than US cashback apps have</li>
      </ul>
    </div>
  </div>
  <div>
    <div class="card">
      <h3>The Market Gap</h3>
      <p>No cashback aggregator exists in Albania. Zero. The market is completely empty. Global players don't operate here.</p>
    </div>
    <div class="card" style="margin-top: 16px;">
      <h3>The Shadow Economy Problem</h3>
      <p>Albania's informal economy is 30-50% of GDP. Consumers don't always demand receipts. A platform that rewards scanning receipts directly supports tax compliance. This is the kind of thing that gets government support.</p>
    </div>
    <div class="card" style="margin-top: 16px;">
      <h3>The Leapfrog Opportunity</h3>
      <p>Less legacy infrastructure to replace. Small population moves faster. Kenya skipped credit cards with M-Pesa. Albania can skip the Visa/Mastercard era.</p>
    </div>
  </div>
</div>
