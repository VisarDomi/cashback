<h2>Two Visions</h2>
<p class="subtitle">The ideal and the realistic. One leads to the other.</p>
<div class="two-col">
  <div class="card">
    <span class="tag tag-blue">Long-term</span>
    <h3 style="color: var(--blue);">Vision A: Albanian Alipay</h3>
    <p>A phone-based payment platform that lets every Albanian pay for everything from their phone. Built on Albania's own infrastructure (e-Albania + fiskalizimi). Not dependent on Apple, Google, or any foreign company.</p>
    <br>
    <p class="dim">This is the endgame. Not the starting point. Requires EMI license, significant capital, and proven traction.</p>
  </div>
  <div class="card">
    <span class="tag tag-green">Start here</span>
    <h3 style="color: var(--green);">Vision B: Loyalty Aggregator</h3>
    <p>Centralize loyalty programs from Albanian companies (Neptun, Conad, BKT, etc.) into one app. Users earn rewards across all partners. Companies get cheaper, better loyalty infrastructure.</p>
    <br>
    <p class="dim">This builds the user base, merchant relationships, and data needed for Vision A. No banking license required.</p>
  </div>
</div>
