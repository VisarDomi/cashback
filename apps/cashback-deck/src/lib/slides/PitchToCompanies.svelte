<h2>The Pitch to Companies</h2>
<p class="subtitle">Why would Neptun, Conad, or BKT join instead of doing their own thing?</p>
<div class="two-col">
  <div>
    <div class="card">
      <h3>The Four Arguments</h3>
      <ul>
        <li><strong>Cost:</strong> Building a loyalty app costs EUR 50-100K+/year per company. Sharing one platform = fraction of the cost.</li>
        <li><strong>Cross-sector earning:</strong> "Earn at Conad, use at Neptun." No single company can offer this alone. Makes the loyalty program more attractive to consumers.</li>
        <li><strong>Data insights:</strong> Learn that your customers also shop at competitor X for certain products. Anonymized, never shared raw.</li>
        <li><strong>Exclusivity / FOMO:</strong> "If you don't join, your competitor will be THE supermarket on the platform your customers already use."</li>
      </ul>
    </div>
  </div>
  <div>
    <div class="card" style="border-color: var(--green);">
      <h3 style="color: var(--green);">The Walk-In Pitch</h3>
      <p style="font-style: italic; color: var(--text-dim); line-height: 1.8;">"How many of your customers come back within a week? Maybe 30%?</p>
      <p style="font-style: italic; color: var(--text-dim); line-height: 1.8;">We make them come back by giving them a reason &mdash; a discount on their next visit, automatically, through the fiscal receipt you already hand them.</p>
      <p style="font-style: italic; color: var(--text-dim); line-height: 1.8;">You don't need anything new &mdash; no hardware, no training. Just a card on your counter and one sentence from your staff.</p>
      <p style="font-style: italic; color: var(--text); line-height: 1.8; font-weight: 600;">3 months free. If it doesn't work, remove the card."</p>
    </div>
    <div class="warning-box" style="margin-top: 16px;">
      <h3>Critical: Long-Term Contracts</h3>
      <p>Nectar died because partners left. From the start: 3 months free, then 3-year exclusive commitment. The exclusivity IS the value &mdash; protect it contractually.</p>
    </div>
