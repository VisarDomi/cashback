  <div class="success-box">
    <h3>Pattern: Thriving in Asia &amp; Emerging Markets</h3>
    <p>South Korea, Japan, Thailand, India, Brazil &mdash; all have successful coalitions with tens of millions of users. These are markets where loyalty tech is still expensive relative to market size.</p>
  </div>
  <div class="warning-box">
    <h3>Pattern: Dying in Western Markets</h3>
    <p>US, UK, Canada, NZ &mdash; coalitions are collapsing. Tech got cheap enough for big companies to run their own. But this does NOT apply to small markets like Albania where businesses can't afford DIY.</p>
