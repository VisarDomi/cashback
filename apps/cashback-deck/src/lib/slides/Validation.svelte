<h2>Validation Plan</h2>
<p class="subtitle">Before writing a single line of code, we prove the idea works.</p>
<div class="two-col">
  <div>
    <h3 style="color: var(--text);">Week 1-2: Technical Validation</h3>
    <div class="card" style="margin-top: 12px;">
      <ul>
        <li>Collect 10+ fiscal receipts from different businesses</li>
        <li>Scan QR codes &mdash; what data comes back from tatime.gov.al?</li>
        <li>Test fature.al API &mdash; sign up, verify a receipt programmatically</li>
        <li>Can we extract merchant identity + amount + date automatically?</li>
      </ul>
      <br>
      <div class="flow-box"><span class="green">If QR scan returns merchant + amount:</span>
  Technical foundation confirmed

<span class="red">If QR scan is blocked or limited:</span>
  Find alternative (direct URL parsing,
  fature.al API, or manual OCR fallback)</div>
    </div>

    <h3 style="color: var(--text); margin-top: 20px;">Week 2-3: Market Research</h3>
    <div class="card" style="margin-top: 12px;">
      <ul>
        <li>List every Albanian company with a loyalty program</li>
        <li>What type? Physical card? App? Points? Cashback?</li>
        <li>How sophisticated is each? (punch card vs. digital)</li>
        <li>Map categories: supermarkets, electronics, fuel, cafes, pharma, telecom</li>
        <li>Identify the #1 company in each category (Payback's "prestige" targets)</li>
      </ul>
    </div>
  </div>
  <div>
    <h3 style="color: var(--text);">Week 3-4: Business Validation</h3>
    <div class="card" style="margin-top: 12px;">
      <p>Talk to <strong>10 business owners</strong>. Not a sales pitch. A conversation.</p>
      <br>
      <p><strong>Questions to ask:</strong></p>
      <ul>
        <li>Do you have a loyalty program? What does it cost you?</li>
        <li>What % of customers are repeat customers?</li>
        <li>Would you join a shared platform if it brought customers back?</li>
        <li>What would make you say yes? What would make you say no?</li>
        <li>How much would you pay per returning customer?</li>
      </ul>
      <br>
      <div class="flow-box"><span class="green">If 6+ out of 10 say "yes, I'd try this":</span>
  Build the MVP

<span class="orange">If 3-5 say yes:</span>
  Refine the pitch, test different angles

<span class="red">If 0-2 say yes:</span>
  Pivot or stop. The idea doesn't work.</div>
    </div>

    <h3 style="color: var(--text); margin-top: 20px;">Week 4: Strategic Conversation</h3>
    <div class="card" style="margin-top: 12px;">
      <ul>
        <li>Contact <strong>EasyPay</strong> &mdash; understand their roadmap, explore partnership</li>
        <li>They have the first open banking license in Albania</li>
        <li>Are they a partner, competitor, or potential acquirer?</li>
        <li>This conversation shapes Phase 3+ of the roadmap</li>
      </ul>
    </div>
  </div>
</div>
