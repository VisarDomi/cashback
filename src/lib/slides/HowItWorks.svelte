    <h3 style="color: var(--text);">Merchant Side</h3>
    <div class="flow-box" style="font-size: 14px;"><span class="highlight">ONBOARDING (one-time, 10 minutes)</span>
Sign up on web dashboard
Set offer: "10% off, max 500 LEK, 7-day expiry"
Receive: counter card + window sticker
Bookmark: merchant verification page

<span class="highlight">DAILY OPERATION</span>
Staff says one sentence when giving receipt:
"Scan for 10% off next time"
That's it. No training needed.

<span class="highlight">WHEN CUSTOMER REDEEMS</span>
Customer shows code on phone
Cashier types 6 chars into bookmarked page
<span class="green">Page shows: "Valid - 10% off, max 500 LEK"</span>
Cashier applies discount manually
No special hardware. No app install.

