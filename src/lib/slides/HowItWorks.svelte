<span class="highlight">RETURN VISIT (the habit-forming moment)</span>
Opens app &rarr; "My Rewards"
Shows 6-character code to cashier
<span class="green">Gets 10% off</span>
Saves 20 LEK by doing almost nothing
Now scans every receipt from every partner

