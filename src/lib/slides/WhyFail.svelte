<h2>Why Coalitions Fail</h2>
<p class="subtitle">Five failure patterns to avoid. Every dead coalition died the same way.</p>
<div class="two-col">
  <div>
    <div class="warning-box">
      <h3>1. Partner Defection Spiral</h3>
      <p>Once one major partner leaves, others follow. <strong>Plenti:</strong> AT&amp;T left Oct 2017 &rarr; Macy's left Feb 2018 &rarr; 5 more left Jan 2018 &rarr; Dead Jul 2018. Seven months from first departure to shutdown.</p>
    </div>
    <div class="warning-box">
      <h3>2. Data Control Conflict</h3>
      <p>Large partners want first-party customer data for personalization, but data sits with the coalition operator. This tension grows as partners get more sophisticated. <strong>Nectar</strong> died partly because Sainsbury's wanted the data for itself.</p>
    </div>
    <div class="warning-box">
      <h3>3. Technology Commoditization</h3>
      <p>Cloud SaaS made standalone programs affordable, eliminating the cost-sharing argument. <strong>Flybuys NZ</strong> CEO: "businesses now have greater access to technology... the Flybuys model has run its course." But this only applies where businesses CAN afford their own tech.</p>
    </div>
  </div>
  <div>
    <div class="warning-box">
      <h3>4. Low Consumer Engagement</h3>
      <p><strong>Plenti:</strong> Half of US consumers surveyed weren't even familiar with it. Low-value currency + complex earn/redeem rules = disengagement. The consumer must understand and feel the value immediately.</p>
    </div>
    <div class="warning-box">
      <h3>5. Points Devaluation / Expiration</h3>
      <p><strong>Air Miles Canada:</strong> Introduced 5-year points expiration in 2011. Massive backlash in 2016 as deadline approached. Triggered partner departures, bankruptcy of parent company, and replacement of entire program.</p>
    </div>
    <div class="success-box">
      <h3>Our Mitigation</h3>
      <ul>
        <li><strong>Long-term exclusive contracts</strong> (3+ years) to prevent defection spiral</li>
        <li><strong>Never share raw data</strong> between partners &mdash; only provide insights</li>
        <li><strong>Albania's market</strong> is too small for businesses to afford DIY &mdash; tech commoditization doesn't kill us</li>
        <li><strong>Simple, instant rewards</strong> &mdash; no complex point systems</li>
      </ul>
    </div>
  </div>
</div>
