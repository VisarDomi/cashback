<h2>Why Coalitions Succeed</h2>
<p class="subtitle">The specific conditions that make loyalty coalitions work.</p>
<div class="three-col">
  <div class="card">
    <h3>1. Cost Sharing</h3>
    <p>Building loyalty tech costs $50K-550K. When 10 companies share one platform, each pays a fraction. This is the core economic argument.</p>
    <br>
    <div class="flow-box">Build your own: <span class="red">~$550,000/yr</span>
Join coalition:  <span class="green">~$29,000/yr</span></div>
    <p class="dim" style="font-size: 14px; margin-top: 8px;">Source: WPLoyalty 2026 Cost Analysis</p>
  </div>
  <div class="card">
    <h3>2. Cross-Sector Earning</h3>
    <p>"Earn at Conad, spend at Neptun" is something no single company can offer alone. This makes the coalition program more attractive to consumers than any individual program.</p>
    <br>
    <p>One airline saw <strong>40% higher redemption</strong> and <strong>20% higher satisfaction</strong> after integrating coalition partners.</p>
  </div>
  <div class="card">
    <h3>3. Category Exclusivity</h3>
    <p>Payback's formula: only ONE company per category. The supermarket, the gas station, the electronics store. This creates:</p>
    <br>
    <ul>
      <li>Prestige ("you're THE electronics partner")</li>
      <li>FOMO ("if you don't join, your competitor will")</li>
      <li>Trust (no direct competitor sees your data)</li>
    </ul>
  </div>
</div>
<div class="two-col" style="margin-top: 20px;">
  <div class="card">
    <h3>4. Data Insights</h3>
    <p>The platform sees shopping behavior across all sectors. A cafe learns that their customers also shop at a specific supermarket. No single company can get this alone. <strong>But raw data is never shared between partners</strong> &mdash; only anonymized insights.</p>
  </div>
  <div class="card">
    <h3>5. Shared Customer Acquisition</h3>
    <p>Every new member who joins through ANY partner becomes available to ALL partners. A user who signs up at the supermarket now sees offers from the cafe, the gas station, the bookstore. Customer acquisition cost is spread across the entire network.</p>
  </div>
</div>
