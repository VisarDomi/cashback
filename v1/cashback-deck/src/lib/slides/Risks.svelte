<h2>Risks &amp; Mitigations</h2>
<p class="subtitle">What could kill this, and how to prevent it.</p>
<div class="two-col">
  <div>
    <div class="warning-box">
      <h3>Companies refuse to join</h3>
      <p>Validate in Phase 0. If 8 out of 10 say no, reconsider or pivot. Don't build first.</p>
    </div>
    <div class="warning-box">
      <h3>Anchor partner leaves (Nectar problem)</h3>
      <p>Long-term exclusive contracts (3+ years) from day one. Make switching costs high. Build dependency.</p>
    </div>
    <div class="warning-box">
      <h3>Someone copies with more connections</h3>
      <p>Move fast. Build traction before talking to politicians. First-mover advantage matters in a small market.</p>
    </div>
  </div>
  <div>
    <div class="warning-box">
      <h3>Receipt fraud (scanning others' receipts)</h3>
      <p>First-claim-only per NIVF. For loyalty rewards (not real money), the risk is low. Tighten in later phases.</p>
    </div>
    <div class="warning-box">
      <h3>Fiskalizimi API access issues</h3>
      <p>Use fature.al third-party API. Or parse QR code data directly (contains a tatime.gov.al verification URL).</p>
    </div>
    <div class="warning-box">
      <h3>Market too small</h3>
      <p>Focus on Tirana first (~800K people). Prove unit economics. Expand to other cities only when Tirana works.</p>
    </div>
  </div>
</div>
