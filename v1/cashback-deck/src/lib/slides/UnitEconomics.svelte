<h2>Unit Economics</h2>
<p class="subtitle">The math that makes this work for merchants, users, and the platform.</p>
<div class="three-col">
  <div class="card" style="border-color: var(--green);">
    <h3 style="color: var(--green);">For the Merchant</h3>
    <div class="flow-box" style="font-size: 13px;"><span class="highlight">Without platform:</span>
Customer visits 2x/month
Revenue: 400 LEK/month

<span class="highlight">With platform:</span>
Customer visits 3x/month
Revenue: 600 LEK/month
Discount given: -20 LEK (10% off)
Platform fee: -30 LEK

<span class="green">Net gain: +150 LEK/month/customer</span>
<span class="green">ROI: 5x return on platform fee</span></div>
    <p class="dim" style="font-size: 13px; margin-top: 8px;">Merchant spends 50 LEK (fee + discount) to earn 200 LEK in extra revenue. Clear positive ROI.</p>
  </div>
  <div class="card" style="border-color: var(--blue);">
    <h3 style="color: var(--blue);">For the User</h3>
    <div class="flow-box" style="font-size: 13px;"><span class="highlight">Scans 4 receipts/month</span>
from 4 different partners

Average discount: 10%
Average spend: 200 LEK/visit

<span class="green">Saves: ~80 LEK/month</span>
<span class="green">~960 LEK/year</span>

<span class="highlight">Effort:</span> 5 seconds per receipt scan
<span class="highlight">Cost:</span> Free app</div>
    <p class="dim" style="font-size: 13px; margin-top: 8px;">Not life-changing money, but free money for zero effort. The consolidation convenience is the real hook.</p>
  </div>
  <div class="card" style="border-color: var(--accent);">
    <h3>For the Platform</h3>
    <div class="flow-box" style="font-size: 13px;"><span class="highlight">30 merchants, each with:</span>
~80 redemptions/month
&times; 30 LEK fee = 2,400 LEK/merchant

<span class="highlight">Monthly revenue:</span>
30 &times; 2,400 = <span class="green">72,000 LEK</span>
                 = <span class="green">~EUR 655/month</span>

<span class="highlight">Monthly costs:</span>
Servers: ~EUR 50
App store: ~EUR 25
Total: ~EUR 75

<span class="green">Net: ~EUR 580/month</span>
<span class="dim">(at 30 merchants)</span></div>
    <p class="dim" style="font-size: 13px; margin-top: 8px;">Not a salary yet. But at 100 merchants: ~EUR 2,200/month. At 300: ~EUR 6,500/month.</p>
  </div>
</div>
