<h2>Lessons From Others</h2>
<p class="subtitle">What worked, what failed, and what almost killed them.</p>
<div class="three-col">
  <div class="card">
    <span class="tag tag-green">Success</span>
    <h3>ShopBack</h3>
    <p><strong>Southeast Asia, 2014</strong></p>
    <p>Pure cashback, grew to 55M users across 13 markets. $332M raised. IPO planned.</p>
    <br>
    <div class="warning-box" style="padding: 12px 16px;">
      <p style="font-size: 14px;"><strong>Almost died:</strong> Tried BNPL payments in 2021. Lost money fast. Fired 24% of staff. CEO apologized publicly. Survived by going back to basics.</p>
    </div>
    <br>
    <p class="dim" style="font-size: 14px;">Lesson: Don't try to become a fintech too early.</p>
  </div>
  <div class="card">
    <span class="tag tag-green">Success</span>
    <h3>Ibotta</h3>
    <p><strong>US, 2011. IPO'd 2024 at $2.7B</strong></p>
    <p>Receipt scanning cashback. Pay-per-sale model eliminated risk for brands.</p>
    <br>
    <p>Key pivot in 2017: stopped being a consumer app, became <strong>B2B marketing infrastructure</strong>. That's what made them worth billions.</p>
    <br>
    <p class="dim" style="font-size: 14px;">Lesson: The consumer app is the entry point. The B2B platform is the real business.</p>
  </div>
  <div class="card">
    <span class="tag tag-red">Warning</span>
    <h3>Nectar (UK)</h3>
    <p><strong>UK, 2002. Coalition loyalty program.</strong></p>
    <p>Launched with half of UK households. Peaked at 16.8M members.</p>
    <br>
    <div class="warning-box" style="padding: 12px 16px;">
      <p style="font-size: 14px;"><strong>What killed it:</strong> Partners left. As loyalty tech got cheaper, companies ran their own programs. Value collapsed from GBP 368M to GBP 60M. <strong>84% destruction.</strong></p>
    </div>
    <br>
    <p class="dim" style="font-size: 14px;">Lesson: Lock in long-term exclusive contracts from day one.</p>
  </div>
</div>
