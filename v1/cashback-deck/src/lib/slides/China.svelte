<h2>China: The Endgame Reference</h2>
<p class="subtitle">How a billion people stopped using cash. And what Albania can learn.</p>
<div class="two-col">
  <div>
    <h3 style="color: var(--text);">What Actually Happened</h3>
    <ul>
      <li><strong>Alipay (2003):</strong> Started as escrow for Taobao. Solved trust in online shopping. Payments came later.</li>
      <li><strong>WeChat Pay (2013):</strong> Embedded in a messaging app 600M people already used. Payments were a feature, not the product.</li>
      <li><strong>QR codes:</strong> Free for merchants (just print a paper). No expensive POS terminals needed. 100M+ small businesses adopted instantly.</li>
      <li><strong>Digital Yuan (2020+):</strong> Government CBDC. Mostly irrelevant to why China is cashless. The revolution was commercial, not governmental.</li>
    </ul>
  </div>
  <div>
    <div class="card" style="border-color: var(--accent);">
      <h3>The Pattern</h3>
      <div class="flow-box"><span class="highlight">1.</span> Solve a real pain point first
   <span class="dim">(trust, convenience, cost)</span>

<span class="highlight">2.</span> Make merchant adoption free
   <span class="dim">(QR codes = zero hardware cost)</span>

<span class="highlight">3.</span> Build on something people already use
   <span class="dim">(don't start with "download our payment app")</span>

<span class="highlight">4.</span> Find a viral adoption moment
   <span class="dim">(WeChat: Red Envelope during New Year)</span>

<span class="highlight">5.</span> Then add payments
   <span class="dim">(only after millions of daily users)</span></div>
    </div>
    <div class="card" style="margin-top: 16px;">
      <h3>Albania's Equivalent</h3>
      <p>Fiskalizimi QR codes are already on every receipt. e-Albania provides digital identity. The infrastructure exists. What's missing is the consumer-facing app that makes it all useful.</p>
