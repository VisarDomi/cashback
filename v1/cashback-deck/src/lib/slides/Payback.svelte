      <h3>The Three Rules That Made It Work</h3>
      <ul>
        <li><strong>Category exclusivity</strong> &mdash; Only one supermarket, one gas station, one electronics retailer. "You're THE electronics partner" is flattering and FOMO-inducing.</li>
        <li><strong>No data sharing between partners</strong> &mdash; The platform sees everything, but Conad never sees what customers buy at Neptun. This is what made competing companies comfortable joining.</li>
        <li><strong>Prestige recruitment</strong> &mdash; Only approached the biggest company in each category. Quality over quantity.</li>
      </ul>
    </div>
